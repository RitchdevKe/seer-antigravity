import { Match } from '../src/types';
import { getMatchEvaluatorTags } from '../src/utils/matchEvaluator';
import { generateSeerSlips } from '../src/utils/seerSlipSelection';
import { getOptimizedScoreDetailed } from '../src/utils/optimizedweights';
import { isBannedFromSeerSlips } from '../src/utils/leagueFilters';

const rdsConfig = {
  host: 'seer-postgres-db-2.c0jo26icsslj.us-east-1.rds.amazonaws.com',
  port: 5432,
  user: 'postgres',
  password: 'SeerAdmin2026!bp6luu',
  database: 'postgres',
  ssl: { rejectUnauthorized: false }
};

async function main() {
  const pool = new Pool(rdsConfig);
  try {
    const res = await pool.query('SELECT data FROM live_matches');
    const matches: Match[] = res.rows.map(r => r.data).filter(Boolean);
    console.log(`Loaded ${matches.length} matches from live_matches.`);

    const phaStatsMap = {};
    const matchStars = {};

    // 1. Check tags across all matches (simulating Live Analysis)
    const taggedTop12 = matches.filter(m => {
      const tags = m.evaluatorTags && m.evaluatorTags.length > 0
        ? m.evaluatorTags
        : getMatchEvaluatorTags(m, phaStatsMap, false, true, matchStars);
      return tags.some(t => t.startsWith('top12:') || t.startsWith('top10:'));
    });

    const taggedUpsets = matches.filter(m => {
      const tags = m.evaluatorTags && m.evaluatorTags.length > 0
        ? m.evaluatorTags
        : getMatchEvaluatorTags(m, phaStatsMap, false, true, matchStars);
      return tags.some(t => t.startsWith('upsets:'));
    });

    const taggedBestBet = matches.filter(m => {
      const tags = m.evaluatorTags && m.evaluatorTags.length > 0
        ? m.evaluatorTags
        : getMatchEvaluatorTags(m, phaStatsMap, false, true, matchStars);
      return tags.some(t => t.startsWith('best_bet:'));
    });

    console.log(`Live Analysis Tagged Matches:`);
    console.log(`- Top 12 (top12/top10): ${taggedTop12.length}`);
    console.log(`- Upsets (upsets:): ${taggedUpsets.length}`);
    console.log(`- Best Bet (best_bet:): ${taggedBestBet.length}`);

    // Check banned count
    console.log(`\nBanned from Seer Slips:`);
    console.log(`- Top 12 banned: ${taggedTop12.filter(isBannedFromSeerSlips).length}`);
    console.log(`- Upsets banned: ${taggedUpsets.filter(isBannedFromSeerSlips).length}`);
    console.log(`- Best Bet banned: ${taggedBestBet.filter(isBannedFromSeerSlips).length}`);

    // Now run generateSeerSlips
    const cleanPool = matches.filter(m => !isBannedFromSeerSlips(m));
    console.log(`\nClean pool for generateSeerSlips: ${cleanPool.length}`);
    const slips = generateSeerSlips(cleanPool, phaStatsMap, matchStars, false, false);

    console.log(`\nSlips Generated by generateSeerSlips:`);
    console.log(`- Top 12 (top_12_value): ${slips.live['top_12_value']?.length || 0} picks`);
    console.log(`- Top 10 (top_10_value): ${slips.live['top_10_value']?.length || 0} picks`);
    console.log(`- Best Bet (best_bet): ${slips.live['best_bet']?.length || 0} picks`);
    console.log(`- Bankers Dlive (bankers_dlive): ${slips.live['bankers_dlive']?.length || 0} picks`);
    console.log(`- Upsets (upsets): ${slips.spec['upsets']?.length || 0} picks`);
    console.log(`- Bankers Jackpot (bankers_jackpot): ${slips.spec['bankers_jackpot']?.length || 0} picks`);
    console.log(`- Value Picks (value_picks): ${slips.spec['value_picks']?.length || 0} picks`);
    console.log(`- Value Bets (value_bets): ${slips.spec['value_bets']?.length || 0} picks`);
    console.log(`- Banker Draws (banker_draws): ${slips.spec['banker_draws']?.length || 0} picks`);

    // Let's check why Upsets has 0
    console.log(`\n--- Deep Dive Upsets (${taggedUpsets.length} tagged) ---`);
    taggedUpsets.forEach(m => {
      const isBanned = isBannedFromSeerSlips(m);
      const score = getOptimizedScoreDetailed(m, 'upsets', phaStatsMap);
      const tags = getMatchEvaluatorTags(m, phaStatsMap, false, true, matchStars);
      console.log(`[Upsets] ID:${m.id} | Banned:${isBanned} | Score:${score.totalScore} (base:${score.baseInfo.points}) | Teams:${m.teams} | Odds:${m.mo}`);
    });

    // Let's check Top 12
    console.log(`\n--- Deep Dive Top 12 (${taggedTop12.length} tagged) ---`);
    taggedTop12.forEach(m => {
      const isBanned = isBannedFromSeerSlips(m);
      const score = getOptimizedScoreDetailed(m, 'top_12_value', phaStatsMap);
      const tags = getMatchEvaluatorTags(m, phaStatsMap, false, true, matchStars);
      console.log(`[Top 12] ID:${m.id} | Banned:${isBanned} | Score:${score.totalScore} (base:${score.baseInfo.points}) | Teams:${m.teams} | Odds:${m.mo}`);
    });

    // Let's check Best Bet
    console.log(`\n--- Deep Dive Best Bet (${taggedBestBet.length} tagged) ---`);
    taggedBestBet.forEach(m => {
      const isBanned = isBannedFromSeerSlips(m);
      const score = getOptimizedScoreDetailed(m, 'best_bet', phaStatsMap);
      console.log(`[Best Bet] ID:${m.id} | Banned:${isBanned} | Score:${score.totalScore} (base:${score.baseInfo.points}) | Teams:${m.teams} | Odds:${m.mo}`);
    });

  } finally {
    await pool.end();
  }
}

main().catch(console.error);
